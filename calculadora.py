def calcular_suma (numero1: float, numero2: float)->float:
    suma = numero1 + numero2
    return suma 

def calcular_resta (numero1: float, numero2: float) -> float:
    resta = numero1 - numero2
    return resta

def calcular_multiplicacion (numero1: float, numero2: float) ->float:
    multiplicacion = numero1 * numero2
    return multiplicacion

def calcular_division (numero1: int, numero2: int)->int:
    division = numero1 / numero2
    return division

